TEXT_NODE = re.compile(r"(?<=>)([^<>]+)(?=<)")

# Nomor halaman footer, mis. "07 / 16" — bentuknya sama di semua halaman.
PAGE_NO = re.compile(r"^\d\d / 16$")


def norm(s: str) -> str:
    return " ".join(s.split())


def main() -> int:
    if not SRC.is_dir():
        print(f"ABORT — folder sumber tidak ada: {SRC}")
        return 1
    DST.mkdir(parents=True, exist_ok=True)

    hits = 0
    missed: list[tuple[str, str]] = []
    files = sorted(SRC.glob("*.slide"))
    if not files:
        print(f"ABORT — tidak ada .slide di {SRC}")
        return 1

    for path in files:
        src = path.read_text(encoding="utf-8")
        out_parts: list[str] = []
        last = 0

        for m in TEXT_NODE.finditer(src):
            raw = m.group(1)
            key = norm(raw)
            if not key:
                continue
            out_parts.append(src[last:m.start(1)])
            if key in MAP:
                out_parts.append(MAP[key])
                hits += 1
            else:
                out_parts.append(raw)
                if (
                    key not in KEEP
                    and not PAGE_NO.match(key)
                    and not key.startswith("{/*")
                ):
                    missed.append((path.name, key))
            last = m.end(1)
        out_parts.append(src[last:])

        (DST / path.name).write_text("".join(out_parts), encoding="utf-8")

    print(f"berkas ditulis : {len(files)} → {DST}")
    print(f"simpul diganti : {hits}")
    if missed:
        print(f"\nBELUM DITERJEMAHKAN ({len(missed)}) — periksa daftar ini:")
        for f, t in missed:
            print(f"  {f}\t{t}")
        return 1
    print("\nSemua simpul teks sudah tertangani.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
